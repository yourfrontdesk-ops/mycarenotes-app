import { useState, useEffect } from 'react';
import { Copy, Check, FileText, AlertCircle, Printer, Save, Pencil, ShieldCheck, X } from 'lucide-react';
import { NoteType, NoteMetadata } from '../types';

interface NoteResultProps {
  note: string;
  error: string;
  noteType?: NoteType;
  metadata?: NoteMetadata;
  onSave?: () => void;
  isSaving?: boolean;
  isSaved?: boolean;
  onNoteChange?: (note: string) => void;
}

export default function NoteResult({
  note,
  error,
  noteType,
  metadata,
  onSave,
  isSaving,
  isSaved,
  onNoteChange,
}: NoteResultProps) {
  const [approved, setApproved] = useState(false);
  const [editing, setEditing] = useState(false);
  const [editValue, setEditValue] = useState(note);
  const [copied, setCopied] = useState(false);

  // Reset approval state whenever a new note arrives
  useEffect(() => {
    setApproved(false);
    setEditing(false);
    setEditValue(note);
  }, [note]);

  const handleApproveAsWritten = () => {
    setApproved(true);
  };

  const handleStartEdit = () => {
    setEditValue(note);
    setEditing(true);
  };

  const handleSaveEdit = () => {
    onNoteChange?.(editValue);
    setEditing(false);
    setApproved(true);
  };

  const handleCancelEdit = () => {
    setEditValue(note);
    setEditing(false);
  };

  const handleCopy = async () => {
    await navigator.clipboard.writeText(note);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    const title = `${noteType ?? 'Care Report'} — ${metadata?.residentName ?? ''}`.trim().replace(/—\s*$/, '');
    const printWindow = window.open('', '_blank');
    if (!printWindow) return;

    printWindow.document.write(`<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${title}</title>
  <style>
    body { font-family: Arial, sans-serif; font-size: 13px; line-height: 1.7; color: #1a1a1a; max-width: 700px; margin: 40px auto; padding: 0 20px; }
    .header { border-bottom: 2px solid #0284c7; padding-bottom: 12px; margin-bottom: 24px; }
    .header h1 { font-size: 18px; color: #0284c7; margin: 0 0 4px 0; }
    .header p { margin: 0; color: #555; font-size: 12px; }
    .note-body { white-space: pre-wrap; }
    .footer { margin-top: 40px; border-top: 1px solid #ddd; padding-top: 12px; font-size: 11px; color: #888; }
    @media print { body { margin: 20px; } }
  </style>
</head>
<body>
  <div class="header">
    <h1>myCareNotes — ${noteType ?? 'Care Report'}</h1>
    <p>CQC-compliant care record &bull; Generated by myCareNotes &bull; Reviewed and approved by care worker</p>
  </div>
  <div class="note-body">${note.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')}</div>
  <div class="footer">
    This report was generated using myCareNotes and reviewed by the care worker prior to use.
  </div>
</body>
</html>`);
    printWindow.document.close();
    printWindow.focus();
    setTimeout(() => printWindow.print(), 250);
  };

  if (error) {
    return (
      <div className="bg-white rounded-2xl border border-red-100 shadow-sm p-6">
        <div className="flex items-start gap-3">
          <div className="w-8 h-8 bg-red-50 rounded-lg flex items-center justify-center flex-shrink-0">
            <AlertCircle size={15} className="text-red-500" />
          </div>
          <div>
            <h3 className="text-sm font-bold text-red-700 mb-1 tracking-tight">Generation Failed</h3>
            <p className="text-sm text-red-600">{error}</p>
          </div>
        </div>
      </div>
    );
  }

  if (!note) return null;

  return (
    <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden">

      {/* Card header */}
      <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between">
        <div className="flex items-center gap-2.5">
          <div className={`w-7 h-7 rounded-lg flex items-center justify-center ${approved ? 'bg-emerald-50' : 'bg-amber-50'}`}>
            <FileText size={14} className={approved ? 'text-emerald-600' : 'text-amber-600'} />
          </div>
          <div>
            <h3 className="text-sm font-bold text-gray-900 tracking-tight">Generated Note</h3>
            <p className="text-xs text-gray-400">
              {approved ? 'Reviewed and approved — ready to copy' : 'Review required before copying to record'}
            </p>
          </div>
        </div>
        {approved ? (
          <span className="text-xs bg-emerald-50 text-emerald-700 font-semibold px-2.5 py-1 rounded-full border border-emerald-100 flex items-center gap-1.5">
            <ShieldCheck size={11} />
            Approved
          </span>
        ) : (
          <span className="text-xs bg-amber-50 text-amber-700 font-semibold px-2.5 py-1 rounded-full border border-amber-100">
            Awaiting Review
          </span>
        )}
      </div>

      {/* Review prompt — only shown before approval */}
      {!approved && !editing && (
        <div className="px-6 pt-4">
          <div className="bg-amber-50 border border-amber-200 rounded-xl px-4 py-3 flex items-start gap-3">
            <AlertCircle size={15} className="text-amber-600 flex-shrink-0 mt-0.5" />
            <p className="text-xs text-amber-800 leading-relaxed">
              <span className="font-semibold">Review this note carefully before approving.</span>{' '}
              Correct anything that does not accurately reflect your original observations before adding to an official record.
            </p>
          </div>
        </div>
      )}

      {/* Note body */}
      <div className="px-6 py-5">
        {editing ? (
          <textarea
            value={editValue}
            onChange={(e) => setEditValue(e.target.value)}
            className="w-full bg-slate-50 rounded-xl px-5 py-4 border border-sky-300 text-sm text-gray-800 leading-relaxed font-mono resize-none focus:outline-none focus:ring-2 focus:ring-sky-200 transition-all"
            rows={Math.max(12, editValue.split('\n').length + 2)}
            autoFocus
          />
        ) : (
          <div className="bg-slate-50 rounded-xl px-5 py-4 border border-slate-100">
            <p className="text-sm text-gray-800 leading-relaxed whitespace-pre-wrap">{note}</p>
          </div>
        )}
      </div>

      {/* Actions */}
      <div className="px-6 pb-5 flex gap-2 flex-wrap">
        {editing ? (
          <>
            <button
              onClick={handleCancelEdit}
              className="flex items-center justify-center gap-2 px-4 py-2.5 border border-slate-200 rounded-xl font-semibold text-sm text-gray-600 hover:bg-slate-50 hover:border-slate-300 transition-all"
            >
              <X size={14} />
              Cancel
            </button>
            <button
              onClick={handleSaveEdit}
              className="flex-1 flex items-center justify-center gap-2 px-6 py-2.5 bg-gray-950 hover:bg-gray-800 text-white rounded-xl font-semibold text-sm transition-all"
            >
              <ShieldCheck size={14} />
              Save &amp; Approve
            </button>
          </>
        ) : approved ? (
          <>
            <button
              onClick={handleStartEdit}
              className="flex items-center justify-center gap-2 px-4 py-2.5 border border-slate-200 rounded-xl font-semibold text-sm text-gray-700 hover:bg-slate-50 hover:border-slate-300 transition-all"
            >
              <Pencil size={14} />
              Edit
            </button>
            {onSave && (
              <button
                onClick={onSave}
                disabled={isSaving || isSaved}
                className={`flex items-center justify-center gap-2 px-4 py-2.5 rounded-xl font-semibold text-sm transition-all border ${
                  isSaved
                    ? 'bg-emerald-50 border-emerald-200 text-emerald-700'
                    : 'border-slate-200 text-gray-700 hover:bg-slate-50 hover:border-slate-300'
                } disabled:opacity-60 disabled:cursor-not-allowed`}
              >
                {isSaved ? <><Check size={14} /> Saved</> : <><Save size={14} /> {isSaving ? 'Saving...' : 'Save'}</>}
              </button>
            )}
            <button
              onClick={handlePrint}
              className="flex items-center justify-center gap-2 px-4 py-2.5 border border-slate-200 rounded-xl font-semibold text-sm text-gray-700 hover:bg-slate-50 hover:border-slate-300 transition-all"
            >
              <Printer size={14} />
              Print
            </button>
            <button
              onClick={handleCopy}
              className={`flex-1 flex items-center justify-center gap-2 px-6 py-2.5 rounded-xl font-semibold text-sm transition-all ${
                copied
                  ? 'bg-emerald-600 text-white'
                  : 'bg-gray-950 hover:bg-gray-800 text-white'
              }`}
            >
              {copied ? <><Check size={14} /> Copied</> : <><Copy size={14} /> Copy Note</>}
            </button>
          </>
        ) : (
          <>
            <button
              onClick={handleStartEdit}
              className="flex items-center justify-center gap-2 px-4 py-2.5 border border-slate-200 rounded-xl font-semibold text-sm text-gray-700 hover:bg-slate-50 hover:border-slate-300 transition-all"
            >
              <Pencil size={14} />
              Edit
            </button>
            <button
              onClick={handleApproveAsWritten}
              className="flex-1 flex items-center justify-center gap-2 px-6 py-2.5 bg-gray-950 hover:bg-gray-800 text-white rounded-xl font-semibold text-sm transition-all"
            >
              <ShieldCheck size={14} />
              Approve &amp; Enable Copy
            </button>
          </>
        )}
      </div>
    </div>
  );
}
