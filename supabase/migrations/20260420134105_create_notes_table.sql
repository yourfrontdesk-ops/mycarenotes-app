/*
  # Create notes table for CareNote AI

  ## Summary
  Creates the core data persistence layer for care notes generated by users.

  ## New Tables

  ### notes
  Stores all AI-generated care notes tied to authenticated users.
  - `id` (uuid, primary key) - unique identifier
  - `user_id` (uuid, FK to auth.users) - the care worker who generated the note
  - `note_type` (text) - type of note: Daily Log, Incident Report, Handover Note, Medication Note
  - `resident_name` (text) - name of the person being supported
  - `care_worker_name` (text) - name of the care worker
  - `shift_time` (text) - shift label e.g. Morning shift
  - `date` (date) - date of the note
  - `time` (text) - time of the note
  - `bullet_points` (text) - the raw notes entered by the worker
  - `generated_note` (text) - the AI-generated professional note
  - `created_at` (timestamptz) - when the record was created

  ## Security
  - RLS enabled on notes table
  - Users can only read, insert, update, delete their own notes
*/

CREATE TABLE IF NOT EXISTS notes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  note_type text NOT NULL DEFAULT 'Daily Log',
  resident_name text NOT NULL DEFAULT '',
  care_worker_name text NOT NULL DEFAULT '',
  shift_time text NOT NULL DEFAULT '',
  date date NOT NULL DEFAULT CURRENT_DATE,
  time text NOT NULL DEFAULT '',
  bullet_points text NOT NULL DEFAULT '',
  generated_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE notes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view own notes"
  ON notes FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own notes"
  ON notes FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update own notes"
  ON notes FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete own notes"
  ON notes FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS notes_user_id_created_at_idx ON notes (user_id, created_at DESC);
